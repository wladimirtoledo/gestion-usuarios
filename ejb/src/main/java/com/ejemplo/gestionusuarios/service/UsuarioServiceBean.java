package com.ejemplo.gestionusuarios.service;

import com.ejemplo.gestionusuarios.dto.UsuarioDTO;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.Date;
import java.util.List;
import javax.annotation.PostConstruct;
import javax.annotation.Resource;
import javax.ejb.EJBException;
import javax.ejb.Stateless;
import javax.sql.DataSource;

@Stateless
public class UsuarioServiceBean implements UsuarioServiceLocal {
    private static final String CREAR_TABLA = "CREATE TABLE IF NOT EXISTS usuarios ("
            + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            + "nombre VARCHAR(150) NOT NULL, "
            + "email VARCHAR(254) NOT NULL, "
            + "fecha_creacion TIMESTAMP NOT NULL)";

    @Resource(lookup = "java:/jdbc/MiDataSource")
    private DataSource dataSource;

    @PostConstruct
    public void inicializarEsquema() {
        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement(CREAR_TABLA)) {
            statement.execute();
        } catch (SQLException exception) {
            throw new EJBException("No se pudo inicializar la tabla de usuarios", exception);
        }
    }

    @Override
    public List<UsuarioDTO> listarUsuarios() {
        String sql = "SELECT id, nombre, email, fecha_creacion FROM usuarios ORDER BY id";
        List<UsuarioDTO> usuarios = new ArrayList<>();

        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql);
             ResultSet resultSet = statement.executeQuery()) {
            while (resultSet.next()) {
                Timestamp fechaCreacion = resultSet.getTimestamp("fecha_creacion");
                usuarios.add(new UsuarioDTO(
                        resultSet.getLong("id"),
                        resultSet.getString("nombre"),
                        resultSet.getString("email"),
                        fechaCreacion == null ? null : new Date(fechaCreacion.getTime())));
            }
        } catch (SQLException exception) {
            throw new EJBException("No se pudo consultar la lista de usuarios", exception);
        }

        return usuarios;
    }

    @Override
    public void crearUsuario(UsuarioDTO usuario) {
        String sql = "INSERT INTO usuarios (nombre, email, fecha_creacion) VALUES (?, ?, ?)";
        Date fechaCreacion = usuario.getFechaCreacion() == null
                ? new Date() : usuario.getFechaCreacion();

        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, usuario.getNombre());
            statement.setString(2, usuario.getEmail());
            statement.setTimestamp(3, new Timestamp(fechaCreacion.getTime()));
            statement.executeUpdate();
        } catch (SQLException exception) {
            throw new EJBException("No se pudo crear el usuario", exception);
        }
    }
}